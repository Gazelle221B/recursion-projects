<?php
declare(strict_types=1);

namespace Restaurants;

use FoodItems\FoodItem;
use Persons\Cashier;
use Persons\Chef;
use Persons\Employee;

class Restaurant
{
    /** @var FoodItem[] */
    private array $menu;
    /** @var Employee[] */
    private array $employees;

    /**
     * @param FoodItem[] $menu
     * @param Employee[] $employees
     */
    public function __construct(array $menu, array $employees)
    {
        $this->menu = $menu;
        $this->employees = $employees;
    }

    /** @return FoodItem[] */
    public function getMenu(): array
    {
        return $this->menu;
    }

    /** @return Employee[] */
    public function getEmployees(): array
    {
        return $this->employees;
    }

    /**
     * Takes the categories the customer wants, lets the cashier create a
     * FoodOrder, delegates cooking to the chef, and returns the Invoice
     * generated by the cashier.
     *
     * @param string[] $categories
     */
    public function order(array $categories): Invoice
    {
        $items = [];
        foreach ($this->menu as $item) {
            if (in_array($item::getCategory(), $categories, true)) {
                $items[] = $item;
            }
        }

        $cashier = $this->findCashier();
        $chef = $this->findChef();

        $order = $cashier->generateOrder($items);
        $chef->prepareFood($order);
        return $cashier->generateInvoice($order);
    }

    private function findCashier(): Cashier
    {
        foreach ($this->employees as $employee) {
            if ($employee instanceof Cashier) {
                return $employee;
            }
        }
        throw new \RuntimeException("No cashier on staff");
    }

    private function findChef(): Chef
    {
        foreach ($this->employees as $employee) {
            if ($employee instanceof Chef) {
                return $employee;
            }
        }
        throw new \RuntimeException("No chef on staff");
    }
}
